import { mkdtemp, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { createBackupArchive } from "./backup-archive";
import { applyBackupRetention } from "./backup-retention";

describe("applyBackupRetention", () => {
    let directory: string;

    beforeEach(async () => {
        directory = await mkdtemp(join(tmpdir(), "talemaster-retention-"));
    });

    afterEach(async () => {
        await rm(directory, { recursive: true, force: true });
    });

    async function createArchive(name: string, createdAt: string, type: "full" | "campaign" = "full") {
        const source = join(directory, `source-${name}`);
        const archive = join(directory, `${name}.zip`);
        await mkdir(source);
        await writeFile(join(source, "payload.txt"), name);
        await createBackupArchive({
            sourceDirectory: source,
            archivePath: archive,
            type,
            ...(type === "campaign" ? { campaignId: "campaign-1" } : {}),
            applicationVersion: "1.0.0",
        });
        // The archive manifest timestamp is generated by the service. Return its path;
        // retention ordering is covered using the timestamp metadata in the manifest.
        return archive;
    }

    it("does not delete older backups until the newly created backup is verified", async () => {
        const first = await createArchive("first", "2026-01-01T00:00:00.000Z");
        const invalid = join(directory, "invalid.zip");
        await writeFile(invalid, "not a zip");

        await expect(
            applyBackupRetention({
                backupDirectory: directory,
                newlyCreatedArchive: invalid,
                keep: 1,
            }),
        ).rejects.toThrow("Retention cannot run because the new backup is invalid");

        await expect(readdir(directory)).resolves.toContain("first.zip");
        await expect(readdir(directory)).resolves.toContain("invalid.zip");
        expect(first).toContain("first.zip");
    });

    it("rejects invalid retention counts", async () => {
        const archive = await createArchive("new", "2026-01-01T00:00:00.000Z");

        await expect(
            applyBackupRetention({
                backupDirectory: directory,
                newlyCreatedArchive: archive,
                keep: 0,
            }),
        ).rejects.toThrow("Backup retention must be a positive safe integer.");
    });

    it("keeps backup scopes separate", async () => {
        const full = await createArchive("full", "2026-01-01T00:00:00.000Z", "full");
        const campaign = await createArchive("campaign", "2026-01-01T00:00:00.000Z", "campaign");

        await applyBackupRetention({
            backupDirectory: directory,
            newlyCreatedArchive: full,
            keep: 1,
        });

        await expect(readdir(directory)).resolves.toContain("campaign.zip");
        await expect(readdir(directory)).resolves.toContain("full.zip");
        expect(campaign).toContain("campaign.zip");
    });
});
